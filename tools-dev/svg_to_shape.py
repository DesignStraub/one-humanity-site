"""Turn the logo SVG (one path: heart outline + continents) into flat polygons
for the 3D gallery.

usage: python3 tools-dev/svg_to_shape.py logo.svg assets/models/world-heart.js
Writes `export default { outer: [[x,y,...]], holes: [[...]] }` in SVG units,
y pointing down. Curves are flattened; tiny wiggles are thinned out.
"""
import re, sys, json

src, dst = sys.argv[1], sys.argv[2]
d = re.search(r' d="([^"]+)"', open(src).read()).group(1)
toks = re.findall(r'[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?', d)

def bez(p0, p1, p2, p3, n):
    out = []
    for i in range(1, n + 1):
        t = i / n; u = 1 - t
        out.append((u**3*p0[0]+3*u*u*t*p1[0]+3*u*t*t*p2[0]+t**3*p3[0],
                    u**3*p0[1]+3*u*u*t*p1[1]+3*u*t*t*p2[1]+t**3*p3[1]))
    return out

polys, cur, pos, start, last_c2, cmd, i = [], [], (0, 0), (0, 0), None, None, 0
def num():
    global i
    v = float(toks[i]); i += 1; return v
while i < len(toks):
    if re.match(r'[A-Za-z]', toks[i]):
        cmd = toks[i]; i += 1
        if cmd in 'Zz':
            if cur: polys.append(cur)
            cur = []; pos = start; last_c2 = None
            continue
    rel = cmd.islower(); c = cmd.upper()
    ox, oy = pos if rel else (0, 0)
    if c == 'M':
        if cur: polys.append(cur)
        pos = (ox + num(), oy + num()); start = pos; cur = [pos]; cmd = 'l' if rel else 'L'; last_c2 = None
    elif c == 'L':
        pos = (ox + num(), oy + num()); cur.append(pos); last_c2 = None
    elif c == 'H':
        pos = ((pos[0] if rel else 0) + num(), pos[1]); cur.append(pos); last_c2 = None
    elif c == 'V':
        pos = (pos[0], (pos[1] if rel else 0) + num()); cur.append(pos); last_c2 = None
    elif c in 'CS':
        if c == 'C':
            c1 = (ox + num(), oy + num())
        else:
            c1 = (2 * pos[0] - last_c2[0], 2 * pos[1] - last_c2[1]) if last_c2 else pos
        c2 = (ox + num(), oy + num()); p = (ox + num(), oy + num())
        L = abs(p[0]-pos[0]) + abs(p[1]-pos[1])
        cur += bez(pos, c1, c2, p, max(2, min(10, int(L / 1.5))))
        pos = p; last_c2 = c2
    else:
        raise SystemExit('unsupported ' + cmd)
if cur: polys.append(cur)

def area(p):
    return sum(p[k][0]*p[k-1][1] - p[k-1][0]*p[k][1] for k in range(len(p))) / 2

def thin(p, tol=0.12):
    out = [p[0]]
    for q in p[1:]:
        if abs(q[0]-out[-1][0]) + abs(q[1]-out[-1][1]) > tol: out.append(q)
    if len(out) > 2 and abs(out[0][0]-out[-1][0]) + abs(out[0][1]-out[-1][1]) < 1e-6: out.pop()
    return out

polys = [thin(p) for p in polys]
polys = [p for p in polys if len(p) >= 3]
polys.sort(key=lambda p: -abs(area(p)))
for p in polys: print(len(p), round(area(p), 1), [round(v,1) for v in p[0]])
outer, holes = polys[0], polys[1:]
flat = lambda p: [round(v, 2) for q in p for v in q]
open(dst, 'w').write('// generated by tools-dev/svg_to_shape.py from the logo (Weltherz)\nexport default ' +
    json.dumps({'outer': flat(outer), 'holes': [flat(h) for h in holes]}, separators=(',', ':')) + ';\n')
